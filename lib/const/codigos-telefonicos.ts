const PREFIJOS_POR_LARGO_DESC = Array.from(
  new Set(CODIGOS_TELEFONICOS.map((c) => c.codigo))
).sort(
  (a, b) => b.length - a.length
)

// Separa un teléfono legacy (puede venir con o sin prefijo, ej. "0999999999" guardado
// antes de este cambio, o "+593999999999") en {prefijo, numero} para precargar un
// PhoneField. Si no reconoce ningún prefijo al inicio del valor, asume Ecuador (+593 —
// el país de la empresa) y deja el valor completo como número.
export function separarTelefono(valor: string): { prefijo: string; numero: string } {
  const limpio = valor.trim()
  if (limpio.startsWith("+")) {
    const prefijo = PREFIJOS_POR_LARGO_DESC.find((codigo) => limpio.startsWith(codigo))
    if (prefijo) return { prefijo, numero: limpio.slice(prefijo.length) }
  }
  return { prefijo: "+593", numero: limpio }
}
